export function collectionImage(imageUrl: string) {
  try {
    const filename = new URL(imageUrl, 'https://local.invalid').pathname
      .split('/')
      .pop();
    return collectionImages.find((image) => image.file === filename);
  } catch {
    return undefined;
  }
}
export function isReferenceImage(description: string) {
  return description.startsWith('Reference image:');
}
export function isDemoCollection(description: string) {
  return description.startsWith('Demo collection:');
}
export function demoCollectionDescription(
  image: CollectionImage,
  sharedBy = 'Maya Laurent',
) {
  return `Demo collection: ${image.title} by ${image.creator} (${image.date}). Public-domain image courtesy of The Metropolitan Museum of Art (CC0). Shared for demonstration by ${sharedBy}; this demo account did not create the artwork.`;
}
export function referenceImageDescription(
  image: CollectionImage,
  original: string,
) {
  return `Reference image: ${image.title} by ${image.creator} (${image.date}). Public-domain image courtesy of The Metropolitan Museum of Art (CC0). The original image is unavailable; this reference is not a reproduction of the original artwork.\n\n${original}`.slice(
    0,
    10000,
  );
}
